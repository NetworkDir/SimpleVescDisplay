#!/usr/bin/env python3
"""
Converts a PNG file into a C header that the firmware can draw as the boot splash.

  python png2header.py my_logo.png ../../firmware/SimpleVescDisplay/src/ui/images/splash_png.h

Any size works - the image is scaled to fit and centred (480x320 looks best on the
3.5" boards, 320x240 on the 2.8" ones). Keep the file small (< 100 KB).

No rebuild needed alternative: copy the image to the SD card as /splash.png or
/splash.jpg - the display shows it instead of the built-in logo.
"""
import struct
import sys


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    src, dst = sys.argv[1], sys.argv[2]
    data = open(src, "rb").read()
    if data[:8] != b"\x89PNG\r\n\x1a\n":
        sys.exit("not a PNG file: " + src)
    width, height = struct.unpack(">II", data[16:24])

    lines = [
        "// Generated by tools/images/png2header.py - do not edit by hand.",
        "// Source image: %dx%d PNG, %d bytes (scaled to fit the screen at boot)" % (width, height, len(data)),
        "#pragma once",
        "#include <stdint.h>",
        "",
        "static const uint8_t splash_png[%d] = {" % len(data),
    ]
    for i in range(0, len(data), 16):
        chunk = data[i:i + 16]
        lines.append("  " + ", ".join("0x%02x" % b for b in chunk) + ",")
    lines.append("};")
    lines.append("")
    open(dst, "w", newline="\n").write("\n".join(lines))
    print("wrote %s (%dx%d, %d bytes)" % (dst, width, height, len(data)))


if __name__ == "__main__":
    main()
